CREATE EDITIONABLE PACKAGE BODY roaz_utils AS

    -- ========================================================================
    -- 1. Gestão dinâmica de diretórios Oracle
    -- ========================================================================
    PROCEDURE create_directory_dynamic_proc(
        p_directory_name  IN VARCHAR2,
        p_directory_path  IN VARCHAR2,
        p_action          IN VARCHAR2 DEFAULT 'CREATE'
    ) IS
    BEGIN
        IF UPPER(p_action) = 'CREATE' THEN
            EXECUTE IMMEDIATE 'CREATE OR REPLACE DIRECTORY ' || p_directory_name ||
                              ' AS ''' || p_directory_path || '''';
        ELSIF UPPER(p_action) = 'DROP' THEN
            EXECUTE IMMEDIATE 'DROP DIRECTORY ' || p_directory_name;
        ELSE
            RAISE_APPLICATION_ERROR(-20001, 'Ação inválida. Use CREATE ou DROP.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(-20002, 'Erro na gestão do diretório: ' || SQLERRM);
    END create_directory_dynamic_proc;

    -- ========================================================================
    -- 2. Gestão dinâmica de tabelas externas (Parquet on-premise)
    -- ========================================================================
    PROCEDURE create_external_table_dynamic_proc(
        p_table_name      IN VARCHAR2,
        p_directory_name  IN VARCHAR2,
        p_parquet_file    IN VARCHAR2,
        p_action          IN VARCHAR2 DEFAULT 'CREATE'
    ) IS
    BEGIN
        IF UPPER(p_action) = 'CREATE' THEN
            EXECUTE IMMEDIATE '
                CREATE TABLE ' || p_table_name || ' (
                    chunk_id   NUMBER,
                    chunk_text CLOB
                )
                ORGANIZATION EXTERNAL (
                    TYPE ORACLE_BIGDATA
                    DEFAULT DIRECTORY ' || p_directory_name || '
                    ACCESS PARAMETERS (
                        com.oracle.bigdata.fileformat = parquet
                    )
                    LOCATION (''' || p_parquet_file || ''')
                )
                PARALLEL 4
                REJECT LIMIT UNLIMITED';
        ELSIF UPPER(p_action) = 'DROP' THEN
            EXECUTE IMMEDIATE 'DROP TABLE ' || p_table_name || ' PURGE';
        ELSE
            RAISE_APPLICATION_ERROR(-20003, 'Ação inválida. Use CREATE ou DROP.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            RAISE_APPLICATION_ERROR(-20004, 'Erro na gestão da tabela externa: ' || SQLERRM);
    END create_external_table_dynamic_proc;

END roaz_utils;
